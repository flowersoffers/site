export function getFallbackCatalogProducts() {
  return PRODUCTS.map((p, idx) => ({
    id: p.id,
    nameEn: p.nameEn,
    nameHi: p.nameHi,
    slug: p.slug,
    sku: `FO-${p.category.toUpperCase().slice(0, 3)}-0${idx + 1}`,
    category: p.category,
    categoryName: FLOWER_CATEGORIES.find((c) => c.id === p.category)?.name || p.category,
    variety: p.nameEn,
    color: "Natural Fresh",
    grade: "Grade A",
    unit: p.unit,
    description: p.description,
    originLocation: p.growingRegion,
    imageUrl: p.imageUrl,
    farmerBasePrice: Math.round(p.pricePerUnit * 0.65),
    wholesalePrice: p.pricePerUnit,
    distributorPrice: Math.round(p.pricePerUnit * 0.85),
    pricePerUnit: p.pricePerUnit,
    retailPrice: Math.round(p.pricePerUnit * 1.25),
    bulkPricePerKg: p.bulkPricePerKg,
    minOrderQty: 1,
    expectedShelfLifeDays: 4,
    isFeatured: p.badge === "bestseller",
    festivalTags: p.festivalTags,
    occasions: p.occasions,
    availableStock: 420,
    inStock: true,
  }));
}
